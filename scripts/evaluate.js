// Evaluates the engine against every scenario's ground-truth labels.
// Reports two seed sets: the TUNING set (seeds 1–20, used while setting thresholds)
// and a HOLD-OUT set (seeds 101–150, never looked at during tuning).
// Writes docs/TEST_RESULTS.md. All numbers are whatever the code actually produces.
import { writeFileSync } from 'node:fs';
import { SCENARIOS } from '../src/sim/scenarios.js';
import { generateSession } from '../src/sim/generator.js';
import { analyzeSession } from '../src/analysis/session.js';
import { PATCHES } from '../src/sim/patches.js';

const pct = (a, b) => (b ? `${((100 * a) / b).toFixed(1)}%` : 'n/a');

function evalSet(start, count) {
  const rows = [];
  let totAgree = 0, totN = 0, unsafe = 0, unsafeN = 0;
  const confusion = {};
  for (const sc of SCENARIOS) {
    let agree = 0, n = 0, naiveFA = 0, naiveN = 0, falseReassure = 0, miss = 0, concN = 0;
    for (let seed = start; seed < start + count; seed++) {
      for (const r of analyzeSession(generateSession(sc, seed))) {
        const exp = sc.expected(r.t1);
        if (exp === 'any') continue;
        n++;
        confusion[`${exp} → ${r.outcome}`] = (confusion[`${exp} → ${r.outcome}`] || 0) + 1;
        if (r.outcome === exp) agree++;
        if (exp !== 'within') { unsafeN++; if (r.outcome === 'within') { unsafe++; falseReassure++; } }
        if (exp === 'concerning') { concN++; if (r.outcome !== 'concerning') miss++; }
        if (exp === 'within') { naiveN++; if (r.naive.flag === 'alarm') naiveFA++; }
      }
    }
    totAgree += agree; totN += n;
    rows.push({ name: sc.name, n, agree, falseReassure, miss, concN, naiveFA, naiveN });
  }
  let md = `| Scenario | Windows | Agreement | False reassurance | Missed "concerning" | Naive chest-only false alarms (in windows that should be normal) |\n|---|---|---|---|---|---|\n`;
  for (const r of rows) md += `| ${r.name} | ${r.n} | ${pct(r.agree, r.n)} | ${r.falseReassure} | ${r.concN ? `${r.miss}/${r.concN}` : '–'} | ${r.naiveN ? pct(r.naiveFA, r.naiveN) : '–'} |\n`;
  md += `\n**Overall agreement:** ${pct(totAgree, totN)} of ${totN} labelled windows. **False reassurance** (expected concerning/insufficient, reported within): ${unsafe}/${unsafeN} (${pct(unsafe, unsafeN)}).\n\n<details><summary>Confusion (expected → reported)</summary>\n\n| Pair | Count |\n|---|---|\n`;
  for (const [k, v] of Object.entries(confusion).sort()) md += `| ${k} | ${v} |\n`;
  return md + `\n</details>\n`;
}

// Patch / control robustness: outcome mix per scenario, with the safety metric
// "false reassurance" = reported within where the Care label is concerning/insufficient.
function mixTable(label, analyzeOpts, genOpts, seeds = 20) {
  let md = `### ${label}\n\n| Scenario | Within | Concerning | Insufficient | False reassurance | False alarm (concerning where label is within) |\n|---|---|---|---|---|---|\n`;
  let U = 0, UN = 0, F = 0, FN = 0;
  for (const sc of SCENARIOS) {
    const c = { within: 0, concerning: 0, insufficient: 0 }; let n = 0, u = 0, f = 0;
    for (let seed = 1; seed <= seeds; seed++) for (const r of analyzeSession(generateSession(sc, seed, genOpts), undefined, analyzeOpts)) {
      const e = sc.expected(r.t1); if (e === 'any') continue;
      n++; c[r.outcome]++;
      if (e !== 'within') { UN++; if (r.outcome === 'within') { u++; U++; } }
      if (e === 'within') { FN++; if (r.outcome === 'concerning') { f++; F++; } }
    }
    md += `| ${sc.name} | ${pct(c.within, n)} | ${pct(c.concerning, n)} | ${pct(c.insufficient, n)} | ${u} | ${f} |\n`;
  }
  return md + `\n**Totals:** false reassurance ${U}/${UN} (${pct(U, UN)}), false alarms ${F}/${FN} (${pct(F, FN)}).\n\n`;
}

const md = `# Test results (synthetic scenarios only)

Generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}. Each scenario is generated with many random seeds; the engine analyses a 30 s window every 10 s. Transition windows (labelled \`any\` in \`src/sim/scenarios.js\`) are excluded from scoring.

## Read this first

- The scenarios, their expected-outcome labels and the engine were all written by the same team. Agreement shows the logic behaves as designed **on its own synthetic data**. It is **not** evidence of clinical accuracy.
- Thresholds were tuned while looking at seeds 1–20. Seeds 101–150 were not used during tuning and are reported separately as a hold-out check against overfitting to particular random draws. They are still drawn from the same generator.
- The "naive" column is a chest-sensor-only estimator with no quality or activity checks, included to show what the artefact handling is for.

## Hold-out seeds (101–150)

${evalSet(101, 50)}
## Tuning seeds (1–20)

${evalSet(1, 20)}
## Patch variants and simulator controls (seeds 1–20)

The tables above use BreatheGuard Care (all three sensors). Quick has no acoustic sensor, so it is not expected to match Care’s labels: replacing “within” or “concerning” with “insufficient” is the honest limitation of fewer sensors. The safety metric is false reassurance (reporting “within” when the label says the situation needs attention).

${mixTable('BreatheGuard Quick (chest + movement)', { channels: PATCHES.quick.channels }, {})}${mixTable('Care with heavy extra noise (noise = 2, the slider maximum)', {}, { noise: 2 })}${mixTable('Care with the movement sensor failed from the start', {}, { failures: [{ sensor: 'motion', from: 0 }] })}${mixTable('Quick with the movement sensor failed from the start', { channels: PATCHES.quick.channels }, { failures: [{ sensor: 'motion', from: 0 }] })}`;
writeFileSync(new URL('../docs/TEST_RESULTS.md', import.meta.url), md);
